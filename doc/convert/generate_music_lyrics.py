# -*- coding: utf-8 -*-
"""Compile up to four standard LRC files into the FPGA subtitle ROM.

Usage: python generate_music_lyrics.py [--lyrics-dir DIR]
Input names: SONG1.LRC .. SONG4.LRC (UTF-8, UTF-8 BOM, or GB18030).
The displayed text is baked into the bitstream; replace an LRC and rebuild.
"""

import argparse
import re
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


HERE = Path(__file__).resolve().parent
HDL = HERE.parent.parent / "src" / "user_source" / "hdl_source"
TIME_TAG = re.compile(r"\[(\d{1,2}):(\d{2})(?:\.(\d{1,3}))?\]")
MAX_GLYPHS = 128
MAX_LINES = 126
MAX_STREAM = 2048
MAX_CHARS_PER_LINE = 14


def read_lrc(path, max_chars=MAX_CHARS_PER_LINE):
    if not path.exists():
        return []
    raw = path.read_bytes()
    try:
        content = raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        content = raw.decode("gb18030")
    lines = {}
    offset_cs = 0
    for source in content.splitlines():
        if source.lower().startswith("[offset:"):
            match = re.match(r"\[offset:([+-]?\d+)\]", source, re.I)
            if match:
                offset_cs = round(int(match.group(1)) / 10)
            continue
        tags = list(TIME_TAG.finditer(source))
        if not tags:
            continue
        text = TIME_TAG.sub("", source).strip()
        if not text:
            continue
        if len(text) > max_chars:
            raise ValueError(f"{path.name}: timed line exceeds {max_chars} characters")
        for tag in tags:
            minute, second = int(tag.group(1)), int(tag.group(2))
            fraction = (tag.group(3) or "0").ljust(2, "0")[:2]
            cs = minute * 6000 + second * 100 + int(fraction) + offset_cs
            if not 0 <= cs <= 65535:
                raise ValueError(f"{path.name}: timestamp out of supported range")
            lines[cs] = text
    return sorted(lines.items())


def glyph_rows(font, char):
    if char == " ":
        return [0] * 16
    image = Image.new("L", (16, 16), 0)
    draw = ImageDraw.Draw(image)
    box = draw.textbbox((0, 0), char, font=font)
    x = (16 - (box[2] - box[0])) // 2 - box[0]
    draw.text((x, 0), char, font=font, fill=255)
    return [sum((1 << (15 - col)) for col in range(16)
                if image.getpixel((col, row)) >= 128) for row in range(16)]


def generate(lyrics_dir, hdl_dir, font_path):
    tracks = [read_lrc(lyrics_dir / f"SONG{i}.LRC") for i in range(1, 5)]
    charset = [" "]
    for track in tracks:
        for _, line in track:
            for char in line:
                if char not in charset:
                    charset.append(char)
    if len(charset) > MAX_GLYPHS:
        raise ValueError(f"{len(charset)} distinct characters; font ROM limit is {MAX_GLYPHS}")
    if sum(map(len, tracks)) > MAX_LINES:
        raise ValueError(f"more than {MAX_LINES} timed lines across four songs")

    index = {char: i for i, char in enumerate(charset)}
    stream = []
    meta = []
    ranges = []
    for track in tracks:
        track_ranges = []
        for pos, (start, line) in enumerate(track):
            if len(stream) + len(line) > MAX_STREAM:
                raise ValueError(f"lyric text exceeds {MAX_STREAM} characters")
            line_index = len(meta)
            meta.append((len(stream), len(line)))
            stream.extend(index[char] for char in line)
            end = track[pos + 1][0] if pos + 1 < len(track) else min(start + 800, 65536)
            track_ranges.append((start, end, line_index))
        ranges.append(track_ranges)

    hdl_dir.mkdir(parents=True, exist_ok=True)
    font = ImageFont.truetype(str(font_path), 16)
    glyphs = [glyph_rows(font, char) for char in charset]
    for bank in range(4):
        path = hdl_dir / f"music_lyric_glyph_b{bank}.mif"
        with path.open("w", encoding="ascii", newline="\n") as out:
            out.write("WIDTH = 18;\nDEPTH = 512;\nADDRESS_RADIX = HEX;\nDATA_RADIX = HEX;\nCONTENT BEGIN\n")
            for address in range(512):
                glyph = bank * 32 + (address >> 4)
                row = address & 15
                value = glyphs[glyph][row] if glyph < len(glyphs) else 0
                out.write(f"{address:03X} : {value:05X};\n")
            out.write("END\n")

    with (hdl_dir / "music_lyric_table.vh").open("w", encoding="ascii", newline="\n") as out:
        out.write("// Generated by generate_music_lyrics.py. Do not edit.\n")
        out.write("localparam [6:0] LYRIC_NONE = 7'd127;\n")
        out.write("function [6:0] line_of_track_cs;\n")
        out.write("  input [1:0] track;\n  input [15:0] cs;\n  begin\n    case (track)\n")
        for track_idx, rows in enumerate(ranges):
            out.write(f"      2'd{track_idx}: begin\n")
            if not rows:
                out.write("        line_of_track_cs = LYRIC_NONE;\n      end\n")
                continue
            for j, (start, end, line_idx) in enumerate(rows):
                prefix = "if" if j == 0 else "else if"
                out.write(f"        {prefix} (cs >= 16'd{start} && cs < 16'd{end}) line_of_track_cs = 7'd{line_idx};\n")
            out.write("        else line_of_track_cs = LYRIC_NONE;\n      end\n")
        out.write("      default: line_of_track_cs = LYRIC_NONE;\n    endcase\n  end\nendfunction\n")
        out.write("function [15:0] line_meta;\n  input [6:0] idx;\n  begin\n    case (idx)\n")
        for idx, (offset, count) in enumerate(meta):
            out.write(f"      7'd{idx}: line_meta = {{11'd{offset}, 5'd{count}}};\n")
        out.write("      default: line_meta = 16'd0;\n    endcase\n  end\nendfunction\n")
        out.write("function [7:0] char_at;\n  input [10:0] pos;\n  begin\n    case (pos)\n")
        for pos, char_idx in enumerate(stream):
            out.write(f"      11'd{pos}: char_at = 8'd{char_idx};\n")
        out.write("      default: char_at = 8'd0;\n    endcase\n  end\nendfunction\n")
    return [len(track) for track in tracks], len(charset), len(stream)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lyrics-dir", type=Path, default=HERE / "lyrics")
    parser.add_argument("--hdl-dir", type=Path, default=HDL)
    parser.add_argument("--font", type=Path, default=Path("C:/Windows/Fonts/simsun.ttc"))
    args = parser.parse_args()
    counts, glyphs, stream_size = generate(args.lyrics_dir, args.hdl_dir, args.font)
    print(f"LRC lines per song: {counts}; glyphs: {glyphs}/128; text: {stream_size}/2048")


if __name__ == "__main__":
    main()
